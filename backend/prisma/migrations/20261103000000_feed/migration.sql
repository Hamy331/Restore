CREATE TABLE "FeedPost" (
 "id" TEXT NOT NULL, "authorId" TEXT NOT NULL, "text" VARCHAR(2000) NOT NULL,
 "imageUrl" TEXT, "listingId" TEXT, "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 "updatedAt" TIMESTAMP(3) NOT NULL, CONSTRAINT "FeedPost_pkey" PRIMARY KEY ("id"),
 CONSTRAINT "FeedPost_authorId_fkey" FOREIGN KEY ("authorId") REFERENCES "User"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT "FeedPost_listingId_fkey" FOREIGN KEY ("listingId") REFERENCES "Listing"("id") ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE TABLE "FeedPostLike" (
 "postId" TEXT NOT NULL, "userId" TEXT NOT NULL, "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY ("postId", "userId"),
 FOREIGN KEY ("postId") REFERENCES "FeedPost"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 FOREIGN KEY ("userId") REFERENCES "User"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE "FeedComment" (
 "id" TEXT NOT NULL, "postId" TEXT NOT NULL, "authorId" TEXT NOT NULL, "text" VARCHAR(2000) NOT NULL,
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, "updatedAt" TIMESTAMP(3) NOT NULL,
 PRIMARY KEY ("id"),
 FOREIGN KEY ("postId") REFERENCES "FeedPost"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 FOREIGN KEY ("authorId") REFERENCES "User"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE "FeedCommentLike" (
 "commentId" TEXT NOT NULL, "userId" TEXT NOT NULL, "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY ("commentId", "userId"),
 FOREIGN KEY ("commentId") REFERENCES "FeedComment"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 FOREIGN KEY ("userId") REFERENCES "User"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX "FeedPost_createdAt_id_idx" ON "FeedPost"("createdAt", "id");
CREATE INDEX "FeedPost_authorId_createdAt_id_idx" ON "FeedPost"("authorId", "createdAt", "id");
CREATE INDEX "FeedComment_postId_createdAt_id_idx" ON "FeedComment"("postId", "createdAt", "id");
ALTER TABLE "FeedPost" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "FeedPostLike" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "FeedComment" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "FeedCommentLike" ENABLE ROW LEVEL SECURITY;
